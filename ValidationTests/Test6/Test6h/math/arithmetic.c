#include "arithmetic.h"

int add(int a, int b) {
    /*
     * Basic addition.
     */
    return a + b;
}

int subtract(int a, int b) {
    /*
     * Basic subtraction.
     */
    return a - b;
}

int multiply(int a, int b) {
    /*
     * Basic multiplication.
     */
    return a * b;
}
